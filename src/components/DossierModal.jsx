import React, { useState } from 'react';
import { 
  X, 
  Copy, 
  Check, 
  Download, 
  ExternalLink, 
  ShieldAlert, 
  FileCheck 
} from 'lucide-react';

export default function DossierModal({ isOpen, onClose, analysisResult, lang }) {
  const [copied, setCopied] = useState(false);

  if (!isOpen || !analysisResult) return null;

  const { riskScore, flags, scannedText, timestamp } = analysisResult;

  // Format complaint text
  const dossierText = `========================================================================
SEBI SCORES 2.0 & CYBERCRIME 1930 / CHAKSHU INCIDENT REPORT
Generated by SATARK (National Investor Scam Interceptor)
Timestamp: ${new Date(timestamp).toLocaleString()}
Incident Threat Score: ${riskScore} / 100 [HIGH RISK INVESTOR FRAUD]
========================================================================

1. INCIDENT OVERVIEW:
Attempted financial fraud detected targeting retail investor via digital channels (WhatsApp/Telegram/SMS). 
The suspect solicited funds / shared deceptive securities claims before money was transferred.

2. SUSPECT COMMUNICATION & VECTOR LOG:
"${scannedText.trim()}"

3. STATUTORY SEBI & LEGAL VIOLATIONS IDENTIFIED:
${flags.map((f, i) => `[${i + 1}] ${f.titleEn}
    - Statutory Reference: ${f.ruleCited || 'SEBI (PFUTP) Regulations, 2003'}
    - Findings: ${f.descEn}`).join('\n\n')}

4. REGULATORY ACTION REQUESTED:
- Verification and blocking of suspect phone numbers / Telegram handles on DoT Chakshu Portal.
- Investigation into beneficiary UPI ID / Mule Bank Account under PMLA and RBI Cybercrime guidelines.
- Issuance of public cautionary notice against fake registration claims under SEBI Act 1992.

5. OFFICIAL REPORTING PORTALS:
- SEBI SCORES Portal: https://scores.sebi.gov.in
- National Cyber Crime Reporting Portal: https://cybercrime.gov.in / Dial 1930
- DoT Chakshu Suspected Fraud Reporting: https://sancharsaathi.gov.in/sfc/
========================================================================`;

  const handleCopy = () => {
    navigator.clipboard.writeText(dossierText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleDownload = () => {
    const element = document.createElement('a');
    const file = new Blob([dossierText], { type: 'text/plain' });
    element.href = URL.createObjectURL(file);
    element.download = `SATARK-Incident-Report-${Date.now()}.txt`;
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/70 backdrop-blur-sm animate-fadeIn">
      <div className="bg-white rounded-2xl shadow-2xl border border-slate-200 w-full max-w-3xl max-h-[90vh] flex flex-col overflow-hidden">
        {/* Header */}
        <div className="bg-slate-900 px-6 py-4 flex items-center justify-between border-b border-slate-800 text-white">
          <div className="flex items-center space-x-2.5">
            <div className="w-8 h-8 rounded-lg bg-rose-500/20 flex items-center justify-center">
              <ShieldAlert className="w-4 h-4 text-rose-400" />
            </div>
            <div>
              <h3 className="text-base font-bold text-white">
                {lang === 'hi' ? 'आधिकारिक सेबी SCORES एवं 1930 शिकायत दस्तावेज' : 'Official SEBI SCORES & Cybercrime Dossier'}
              </h3>
              <p className="text-[11px] text-slate-400">
                {lang === 'hi' ? 'साइबर सेल या सेबी पोर्टल पर तुरंत दर्ज करने हेतु फॉर्मेट' : 'Ready-to-file incident dossier with timestamped legal evidence'}
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="text-slate-400 hover:text-white p-1 rounded-lg hover:bg-slate-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Body */}
        <div className="p-6 overflow-y-auto space-y-4">
          <div className="bg-emerald-50 border border-emerald-200 p-3.5 rounded-xl text-xs text-emerald-900 flex items-center justify-between">
            <div className="flex items-center space-x-2">
              <FileCheck className="w-4 h-4 text-emerald-700 shrink-0" />
              <span>
                {lang === 'hi'
                  ? 'यह दस्तावेज सेबी SCORES 2.0 और राष्ट्रीय साइबर पोर्टल (1930) के मानकों पर तैयार किया गया है।'
                  : 'Pre-formatted according to SEBI SCORES 2.0 & National Cyber Crime Reporting standards.'}
              </span>
            </div>
          </div>

          <div>
            <label className="block text-xs font-bold text-slate-700 uppercase tracking-wide mb-1.5">
              {lang === 'hi' ? 'दस्तावेज पूर्वावलोकन (Pre-filled Text)' : 'Generated Evidence Report'}
            </label>
            <pre className="w-full text-xs font-mono p-4 bg-slate-900 text-emerald-300 rounded-xl overflow-x-auto max-h-80 border border-slate-800 whitespace-pre-wrap leading-relaxed shadow-inner">
              {dossierText}
            </pre>
          </div>

          {/* Action Links */}
          <div className="flex flex-wrap items-center gap-3 pt-2">
            <a
              href="https://scores.sebi.gov.in"
              target="_blank"
              rel="noopener noreferrer"
              className="inline-flex items-center space-x-1.5 text-xs text-emerald-700 hover:text-emerald-800 font-semibold bg-emerald-50 px-3 py-2 rounded-lg border border-emerald-200 transition"
            >
              <span>{lang === 'hi' ? 'सेबी SCORES पोर्टल खोलें' : 'Open SEBI SCORES 2.0'}</span>
              <ExternalLink className="w-3.5 h-3.5" />
            </a>

            <a
              href="https://cybercrime.gov.in"
              target="_blank"
              rel="noopener noreferrer"
              className="inline-flex items-center space-x-1.5 text-xs text-blue-700 hover:text-blue-800 font-semibold bg-blue-50 px-3 py-2 rounded-lg border border-blue-200 transition"
            >
              <span>{lang === 'hi' ? 'राष्ट्रीय साइबर अपराध पोर्टल' : 'Open CyberCrime.gov.in'}</span>
              <ExternalLink className="w-3.5 h-3.5" />
            </a>
          </div>
        </div>

        {/* Footer actions */}
        <div className="bg-neutral-50/80 px-6 py-4 border-t border-neutral-200/80 flex flex-wrap items-center justify-between gap-3">
          <button
            onClick={onClose}
            className="text-xs font-medium text-neutral-600 hover:text-neutral-900 px-4 py-2"
          >
            {lang === 'hi' ? 'बंद करें' : 'Close'}
          </button>

          <div className="flex items-center space-x-3">
            <button
              onClick={handleDownload}
              className="inline-flex items-center space-x-1.5 text-xs font-medium text-[#171717] bg-white hover:bg-neutral-50 px-4 py-2 rounded-full border border-neutral-200 transition shadow-sm"
            >
              <Download className="w-4 h-4" />
              <span>{lang === 'hi' ? 'डाउनलोड करें (.txt)' : 'Download Report'}</span>
            </button>

            <button
              onClick={handleCopy}
              className={`inline-flex items-center space-x-1.5 text-xs font-medium px-5 py-2 rounded-full transition shadow-sm ${
                copied 
                  ? 'bg-emerald-600 text-white' 
                  : 'bg-[#171717] hover:bg-neutral-800 text-white'
              }`}
            >
              {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
              <span>{copied ? (lang === 'hi' ? 'कॉपी कर लिया गया!' : 'Copied!') : (lang === 'hi' ? 'कॉपी करें' : 'Copy All')}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
